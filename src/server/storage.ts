import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import { COLLECTIONS, type CollectionSlug } from "@/lib/collection-defs";
import { getExtension, validateFile } from "@/lib/files";
import { formatId, parseSeq } from "@/lib/ids";
import type { BaseRecord, CollectionData, CollectionSnapshot, StoredFile } from "@/types/records";

/**
 * Local-disk storage for the dashboard:
 *   data/<slug>.json              records + ID counter for one tab
 *   data/uploads/<slug>/<file>    uploaded files
 */
const DATA_DIR = process.env.SHIP_DATA_DIR ?? path.join(process.cwd(), "data");
const NAME_MAX = 100;
/** Stored file names are generated by us, e.g. "LD-001-image-9f2c1a7b.png". */
const STORED_NAME = /^[A-Z]+-\d+-[A-Za-z]+-[0-9a-f]{8}\.[a-z0-9]+$/;

type StoredRecord = BaseRecord & Record<string, unknown>;

/** An error whose message is safe to show to the user. */
export class ApiError extends Error {
  constructor(
    public status: number,
    message: string,
  ) {
    super(message);
  }
}

// Writes to a collection are serialized so concurrent requests can't hand out the same ID.
// Kept on globalThis so every route bundle in this process shares the same queue.
const locks: Map<string, Promise<unknown>> = ((globalThis as { __shipLocks?: Map<string, Promise<unknown>> })
  .__shipLocks ??= new Map());

function withLock<R>(slug: CollectionSlug, task: () => Promise<R>): Promise<R> {
  const previous = locks.get(slug) ?? Promise.resolve();
  const next = previous.then(task, task);
  locks.set(slug, next.catch(() => undefined));
  return next;
}

const dataFile = (slug: CollectionSlug) => path.join(DATA_DIR, `${slug}.json`);
const uploadDir = (slug: CollectionSlug) => path.join(DATA_DIR, "uploads", slug);

async function readData(slug: CollectionSlug): Promise<CollectionData<StoredRecord>> {
  let data: Partial<CollectionData<StoredRecord>> = {};
  try {
    data = JSON.parse(await fs.readFile(dataFile(slug), "utf8"));
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
  }
  const items = Array.isArray(data.items) ? data.items : [];
  const { idPrefix } = COLLECTIONS[slug];
  // Never hand out an ID at or below an existing one, even if the file was edited by hand.
  const maxSeq = items.reduce((max, item) => Math.max(max, parseSeq(idPrefix, item.id) ?? 0), 0);
  return { version: 1, nextSeq: Math.max(data.nextSeq ?? 1, maxSeq + 1), items };
}

/** Atomic write: a crash mid-write can't leave a half-written JSON file. */
async function writeData(slug: CollectionSlug, data: CollectionData<StoredRecord>) {
  await fs.mkdir(DATA_DIR, { recursive: true });
  const target = dataFile(slug);
  const temp = `${target}.${crypto.randomBytes(4).toString("hex")}.tmp`;
  await fs.writeFile(temp, JSON.stringify(data, null, 2), "utf8");
  await fs.rename(temp, target);
}

function fileFieldsOf(slug: CollectionSlug) {
  return Object.entries(COLLECTIONS[slug].fileFields);
}

function toSnapshot(slug: CollectionSlug, data: CollectionData<StoredRecord>): CollectionSnapshot<StoredRecord> {
  const keys = fileFieldsOf(slug).map(([key]) => key);
  const totalBytes = data.items.reduce(
    (sum, item) => sum + keys.reduce((s, key) => s + ((item[key] as StoredFile | undefined)?.size ?? 0), 0),
    0,
  );
  return { items: data.items, nextSeq: data.nextSeq, totalBytes };
}

export async function getSnapshot(slug: CollectionSlug) {
  return toSnapshot(slug, await readData(slug));
}

function parseName(form: FormData): string {
  const raw = form.get("name");
  const name = typeof raw === "string" ? raw.trim() : "";
  if (!name) throw new ApiError(400, "Name is required.");
  if (name.length > NAME_MAX) throw new ApiError(400, `Name must be ${NAME_MAX} characters or fewer.`);
  return name;
}

/** Validates the uploaded files. Missing files are an error only when `required`. */
function parseFiles(slug: CollectionSlug, form: FormData, required: boolean): Map<string, File> {
  const files = new Map<string, File>();
  for (const [key, rule] of fileFieldsOf(slug)) {
    const value = form.get(key);
    if (!(value instanceof File) || value.size === 0) {
      if (required) throw new ApiError(400, `A file for "${key}" is required.`);
      continue;
    }
    const problem = validateFile(value, rule);
    if (problem) throw new ApiError(400, problem);
    files.set(key, value);
  }
  return files;
}

async function saveUpload(slug: CollectionSlug, id: string, field: string, file: File): Promise<StoredFile> {
  const extension = getExtension(file.name);
  const storedName = `${id}-${field}-${crypto.randomBytes(4).toString("hex")}.${extension}`;
  await fs.mkdir(uploadDir(slug), { recursive: true });
  await fs.writeFile(path.join(uploadDir(slug), storedName), Buffer.from(await file.arrayBuffer()));
  return {
    name: file.name,
    size: file.size,
    type: file.type || "application/octet-stream",
    extension,
    storedName,
    url: `/api/files/${slug}/${storedName}`,
    uploadedAt: new Date().toISOString(),
  };
}

async function deleteUploads(slug: CollectionSlug, files: StoredFile[]) {
  await Promise.all(
    files.map((file) =>
      STORED_NAME.test(file.storedName)
        ? fs.rm(path.join(uploadDir(slug), file.storedName), { force: true })
        : undefined,
    ),
  );
}

/** Saves all uploads, or removes the ones already written if any of them fails. */
async function saveUploads(slug: CollectionSlug, id: string, files: Map<string, File>) {
  const saved: Record<string, StoredFile> = {};
  try {
    for (const [field, file] of files) saved[field] = await saveUpload(slug, id, field, file);
  } catch (error) {
    await deleteUploads(slug, Object.values(saved));
    throw error;
  }
  return saved;
}

export function createRecord(slug: CollectionSlug, form: FormData) {
  const name = parseName(form);
  const files = parseFiles(slug, form, true);
  return withLock(slug, async () => {
    const data = await readData(slug);
    const id = formatId(COLLECTIONS[slug].idPrefix, data.nextSeq);
    const saved = await saveUploads(slug, id, files);
    const now = new Date().toISOString();
    const record: StoredRecord = { id, name, ...saved, createdAt: now, updatedAt: now };
    const next = { ...data, nextSeq: data.nextSeq + 1, items: [...data.items, record] };
    try {
      await writeData(slug, next);
    } catch (error) {
      await deleteUploads(slug, Object.values(saved));
      throw error;
    }
    return { record, snapshot: toSnapshot(slug, next) };
  });
}

export function updateRecord(slug: CollectionSlug, id: string, form: FormData) {
  const name = parseName(form);
  const files = parseFiles(slug, form, false);
  return withLock(slug, async () => {
    const data = await readData(slug);
    const existing = data.items.find((item) => item.id === id);
    if (!existing) throw new ApiError(404, `${id} no longer exists.`);
    const saved = await saveUploads(slug, id, files);
    // Fields without a new upload keep their existing file.
    const record: StoredRecord = { ...existing, ...saved, id, name, updatedAt: new Date().toISOString() };
    const next = { ...data, items: data.items.map((item) => (item.id === id ? record : item)) };
    try {
      await writeData(slug, next);
    } catch (error) {
      await deleteUploads(slug, Object.values(saved));
      throw error;
    }
    // Only remove replaced files once the new record is safely written.
    await deleteUploads(slug, Object.keys(saved).map((key) => existing[key] as StoredFile));
    return { record, snapshot: toSnapshot(slug, next) };
  });
}

export function deleteRecord(slug: CollectionSlug, id: string) {
  return withLock(slug, async () => {
    const data = await readData(slug);
    const existing = data.items.find((item) => item.id === id);
    if (!existing) throw new ApiError(404, `${id} no longer exists.`);
    const next = { ...data, items: data.items.filter((item) => item.id !== id) };
    await writeData(slug, next);
    await deleteUploads(
      slug,
      fileFieldsOf(slug).map(([key]) => existing[key] as StoredFile),
    );
    return { snapshot: toSnapshot(slug, next) };
  });
}

const CONTENT_TYPES: Record<string, string> = {
  png: "image/png",
  jpg: "image/jpeg",
  jpeg: "image/jpeg",
  webp: "image/webp",
  svg: "image/svg+xml",
  pdf: "application/pdf",
};

export async function readUpload(slug: CollectionSlug, storedName: string) {
  if (!STORED_NAME.test(storedName)) throw new ApiError(404, "File not found.");
  try {
    const bytes = await fs.readFile(path.join(uploadDir(slug), storedName));
    const contentType = CONTENT_TYPES[getExtension(storedName)] ?? "application/octet-stream";
    return { bytes, contentType };
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") throw new ApiError(404, "File not found.");
    throw error;
  }
}
