/**
 * Storage for the Library, inside each ship's viewer project so the viewer can use the files:
 *   child/ships/<ship>/ship.json                    one project (ship): made from child/template, plus this file
 *   child/ships/<ship>/<dir>/<folder>/<metaFile>    one of its records, e.g. .../src/sections/engine-room/section.json
 *   child/ships/<ship>/<dir>/<folder>/<file>        that record's uploaded files, e.g. lineDiagram-9f2c1a7b.png, or for
 *                                                   an object fuel-pump-2d-77aa01ff.png and fuel-pump-3d-3be0d14c.glb
 *   <collection folder>/next-id.json                ID counter, so IDs are never reused (one per ship for sections and objects)
 * Ship and section folders are named from the name and keep the ID ("SHP-001") in their metadata file; an object's folder is its ID.
 * A section's manual is also read into manual-data.json in its folder, each time one is uploaded.
 * Uploading a section's line diagram queues the generation of its React code (`codegen` in section.json); the API
 * routes then start it (see src/server/codegen/jobs.ts), and the generated files are written into the folders here.
 * Any other files in a record's folder (e.g. a diagram.ts written in the editor) are left alone, until the record is deleted.
 */
const NAME_MAX = 100;
/**
 * Stored file names are generated by us: "<field>-<unique>.<ext>", e.g. "lineDiagram-9f2c1a7b.png", or for a field with
 * a view (an object's files) VIEW_FILE_NAME, e.g. "fuel-pump-3d-3be0d14c.glb". Objects saved before views have the first.
 */
const FIELD_FILE_NAME = /^[A-Za-z]+-[0-9a-f]{8}\.[a-z0-9]+$/;
const isStoredName = (name: string) => FIELD_FILE_NAME.test(name) || VIEW_FILE_NAME.test(name);
/** Windows device names, which can't be used as folder names. */
const DEVICE_NAME = /^(con|prn|aux|nul|com\d|lpt\d)$/i;
/** Added to each project when it's listed, never saved: they follow from what's in its folder. */
const DERIVED_KEYS = ["folder", "sectionCount", "objectCount"];

type StoredRecord = BaseRecord & Record<string, unknown>;

interface CollectionData {
  nextSeq: number;
  /** Oldest first. */
  items: StoredRecord[];
}

/** Where a collection's records are. */
interface Scope {
  slug: CollectionSlug;
  /** Folder holding the record folders, relative to child/, e.g. "ships/mv-aurora/src/sections". */
  dir: string;
  /** The ship the records belong to, e.g. "mv-aurora". Unset for the projects themselves. */
  projectFolder?: string;
}

/** An error whose message is safe to show to the user. */
export class ApiError extends Error {
  constructor(
    public status: number,
    message: string,
  ) {
    super(message);
  }
}

// All writes go through one queue, so concurrent requests can't hand out the same ID, and a ship can't be
// deleted halfway through a save inside it. Kept on globalThis so every route bundle in this process shares it.
const queue: { tail: Promise<unknown> } = ((globalThis as { __shipWriteQueue?: { tail: Promise<unknown> } })
  .__shipWriteQueue ??= { tail: Promise.resolve() });

function withLock<R>(task: () => Promise<R>): Promise<R> {
  const next = queue.tail.then(task, task);
  queue.tail = next.catch(() => undefined);
  return next;
}

const PROJECTS: Scope = { slug: "projects", dir: collectionDir("projects") };

function projectScope(slug: ProjectCollectionSlug, projectFolder: string): Scope {
  return { slug, dir: collectionDir(slug, projectFolder), projectFolder };
}

/** Another collection next to this one, e.g. a ship's objects from its sections. */
function siblingScope(scope: Scope, slug: CollectionSlug): Scope {
  if (slug === "projects") return PROJECTS;
  if (!scope.projectFolder) throw new Error(`${slug} belong to a project`);
  return projectScope(slug, scope.projectFolder);
}

/** The scope of a collection: the projects, or a collection inside the project with this ID (404 if it's gone). */
async function resolveScope(slug: CollectionSlug, projectId?: string): Promise<Scope> {
  if (slug === "projects") return PROJECTS;
  if (!projectId) throw new Error(`${slug} belong to a project`);
  const project = (await readData(PROJECTS)).items.find((item) => item.id === projectId);
  if (!project) throw new ApiError(404, `${projectId} no longer exists.`);
  return projectScope(slug, project.folder);
}

const rootDir = (scope: Scope) => path.join(CHILD_DIR, ...scope.dir.split("/"));
// Only called with names that passed isFolderName, so the folder is always directly inside rootDir.
const recordDir = (scope: Scope, folder: string) => path.join(rootDir(scope), folder);
const fileUrl = (scope: Scope, folder: string, storedName: string) =>
  `/api/files/${encodeURIComponent(scope.projectFolder ?? "")}/${scope.slug}/${encodeURIComponent(folder)}/${storedName}`;

/** Whether `id` has the shape of a record ID, e.g. "SEC-001". */
function isRecordId(slug: CollectionSlug, id: string): boolean {
  return parseSeq(collectionDef(slug).idPrefix, id) !== null;
}

/** Whether `name` has the shape of a record folder's name: made from a name ("engine-room") or an ID ("OBJ-001"). */
function isFolderName(slug: CollectionSlug, name: string): boolean {
  if (!collectionDef(slug).folderFromName) return isRecordId(slug, name);
  return name.length <= SLUG_MAX && SLUG_PATTERN.test(name) && !DEVICE_NAME.test(name);
}

function fileFieldsOf(slug: CollectionSlug) {
  return Object.entries(collectionDef(slug).fileFields);
}

function textFieldsOf(slug: CollectionSlug) {
  return Object.entries(collectionDef(slug).textFields ?? {});
}

function linkKeysOf(slug: CollectionSlug) {
  return Object.keys(collectionDef(slug).links ?? {});
}

/**
 * A file entry from a metadata file, or undefined if it's missing or malformed. The URL is always rebuilt, and the view
 * comes from the field (`view`), so files saved before views get it too.
 */
function readStoredFile(scope: Scope, folder: string, value: unknown, view?: DiagramView): StoredFile | undefined {
  if (!value || typeof value !== "object") return undefined;
  const file = value as Record<string, unknown>;
  if (typeof file.storedName !== "string" || !isStoredName(file.storedName)) return undefined;
  return {
    name: typeof file.name === "string" ? file.name : file.storedName,
    size: typeof file.size === "number" ? file.size : 0,
    type: typeof file.type === "string" ? file.type : "application/octet-stream",
    extension: getExtension(file.storedName),
    storedName: file.storedName,
    url: fileUrl(scope, folder, file.storedName),
    uploadedAt: typeof file.uploadedAt === "string" ? file.uploadedAt : "",
    ...(view && { view }),
  };
}

/** Checks a parsed metadata file. Unknown keys are kept, so fields added by hand survive a save. */
function parseRecord(scope: Scope, folder: string, raw: unknown): StoredRecord {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) throw new Error("it isn't a JSON object");
  const meta = raw as Record<string, unknown>;
  const { slug } = scope;
  const { idPrefix, folderFromName } = collectionDef(slug);
  // A folder named after the ID decides the ID, whatever the file says.
  const id = folderFromName ? meta.id : folder;
  if (typeof id !== "string" || !isRecordId(slug, id)) {
    throw new Error(`it has no valid ID (like "${formatId(idPrefix, 1)}")`);
  }
  if (typeof meta.name !== "string" || !meta.name.trim()) throw new Error("it has no name");
  const createdAt = typeof meta.createdAt === "string" ? meta.createdAt : "";
  const record: StoredRecord = {
    ...meta,
    id,
    folder,
    name: meta.name,
    createdAt,
    updatedAt: typeof meta.updatedAt === "string" ? meta.updatedAt : createdAt,
  };
  for (const [key, field] of fileFieldsOf(slug)) {
    const file = readStoredFile(scope, folder, meta[key], field.view);
    if (file) record[key] = file;
    else if (field.required) throw new Error(`its "${key}" file is missing`);
    else delete record[key];
  }
  for (const [key] of textFieldsOf(slug)) {
    if (typeof meta[key] !== "string" || !meta[key]) delete record[key];
  }
  for (const key of linkKeysOf(slug)) {
    const value = meta[key];
    record[key] = Array.isArray(value) ? [...new Set(value.filter((v): v is string => typeof v === "string"))] : [];
  }
  return record;
}

/** One record, or null if its folder has no readable metadata file (e.g. it's still being created, or was edited badly). */
async function readRecord(scope: Scope, folder: string): Promise<StoredRecord | null> {
  const { metaFile } = collectionDef(scope.slug);
  let text: string;
  try {
    text = await fs.readFile(path.join(recordDir(scope, folder), metaFile), "utf8");
  } catch (error) {
    if (["ENOENT", "ENOTDIR"].includes(errorCode(error) ?? "")) return null;
    throw error;
  }
  try {
    return parseRecord(scope, folder, JSON.parse(text));
  } catch (error) {
    console.warn(`Skipping child/${scope.dir}/${folder}/${metaFile}: ${error instanceof Error ? error.message : error}.`);
    return null;
  }
}

async function readCounter(scope: Scope): Promise<number> {
  try {
    const { nextSeq } = JSON.parse(await fs.readFile(path.join(rootDir(scope), COUNTER_FILE), "utf8"));
    return Number.isSafeInteger(nextSeq) && nextSeq > 0 ? nextSeq : 1;
  } catch (error) {
    if (errorCode(error) === "ENOENT" || error instanceof SyntaxError) return 1;
    throw error;
  }
}

async function readData(scope: Scope): Promise<CollectionData> {
  let entries: Dirent[] = [];
  try {
    entries = await fs.readdir(rootDir(scope), { withFileTypes: true });
  } catch (error) {
    if (errorCode(error) !== "ENOENT") throw error;
  }
  const { slug } = scope;
  const { idPrefix, folderFromName, metaFile } = collectionDef(slug);
  // Symlinks and junctions aren't directories here, so they're never read or deleted.
  const folders = entries.filter((entry) => entry.isDirectory() && isFolderName(slug, entry.name)).map((entry) => entry.name);
  const records = (await Promise.all(folders.map((folder) => readRecord(scope, folder)))).filter((item) => item !== null);
  records.sort((a, b) => a.createdAt.localeCompare(b.createdAt) || a.id.localeCompare(b.id));

  // IDs are unique: if two folders claim the same one (e.g. a section.json copied by hand), the older keeps it.
  const taken = new Set<string>();
  const items = records.filter((record) => {
    if (taken.has(record.id)) {
      console.warn(`Skipping child/${scope.dir}/${record.folder}/${metaFile}: ${record.id} is already used by another folder.`);
      return false;
    }
    taken.add(record.id);
    return true;
  });

  // Never hand out an ID at or below an existing one, even if the counter file was lost.
  // Folders named after IDs count even without a readable metadata file.
  const known = folderFromName ? records.map((record) => record.id) : folders;
  const maxSeq = known.reduce((max, id) => Math.max(max, parseSeq(idPrefix, id) ?? 0), 0);
  return { nextSeq: Math.max(await readCounter(scope), maxSeq + 1), items };
}

/** The metadata file as saved: the folder, counts and file URLs are left out, since they follow from where the file is. */
function toDisk(slug: CollectionSlug, record: StoredRecord) {
  const out: Record<string, unknown> = { ...record };
  for (const key of DERIVED_KEYS) delete out[key];
  for (const [key] of fileFieldsOf(slug)) {
    const file = record[key] as StoredFile | undefined;
    if (!file) continue;
    const { name, size, type, extension, storedName, uploadedAt, view } = file;
    out[key] = { name, size, type, extension, storedName, uploadedAt, ...(view && { view }) };
  }
  return out;
}

/** Written last when saving, and in one step: the viewer only lists a record once this file exists. */
async function writeRecord(scope: Scope, record: StoredRecord) {
  const target = path.join(recordDir(scope, record.folder), collectionDef(scope.slug).metaFile);
  await writeAtomic(target, `${JSON.stringify(toDisk(scope.slug, record), null, 2)}\n`);
}

/** Retries briefly, since on Windows a file watcher (e.g. the child's dev server) can hold files for a moment. */
function removeFolder(dir: string) {
  return fs.rm(dir, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
}

/** A project with how many sections and objects it has. */
async function withCounts(project: StoredRecord): Promise<StoredRecord> {
  const [sectionCount, objectCount] = await Promise.all(
    (["sections", "objects"] as const).map(async (slug) => (await readData(projectScope(slug, project.folder))).items.length),
  );
  return { ...project, sectionCount, objectCount };
}

/**
 * A section with its code generation as the Library shows it: live progress, interrupted runs, and only readable
 * versions (section.json can be edited by hand). Never saved.
 */
function withLiveCodegen(section: StoredRecord): StoredRecord {
  const { codegen, codegenVersions, codegenVersion, ...rest } = section;
  const shown = presentCodegen(codegen);
  const versions = readCodegenVersions(codegenVersions);
  const active = readActiveVersion(codegenVersion);
  return {
    ...rest,
    ...(shown && { codegen: shown }),
    ...(versions.length > 0 && { codegenVersions: versions }),
    ...(active !== undefined && { codegenVersion: active }),
  };
}

async function toSnapshot(scope: Scope, data: CollectionData): Promise<CollectionSnapshot<StoredRecord>> {
  const items =
    scope.slug === "projects"
      ? await Promise.all(data.items.map(withCounts))
      : scope.slug === "sections"
        ? data.items.map(withLiveCodegen)
        : data.items;
  const keys = fileFieldsOf(scope.slug).map(([key]) => key);
  const totalBytes = items.reduce(
    (sum, item) => sum + keys.reduce((s, key) => s + ((item[key] as StoredFile | undefined)?.size ?? 0), 0),
    0,
  );
  return { items, nextSeq: data.nextSeq, totalBytes };
}

/** A save's result: the record as listed (projects with their counts), and the whole collection. */
async function savedResult(scope: Scope, data: CollectionData, record: StoredRecord) {
  const snapshot = await toSnapshot(scope, data);
  return { record: snapshot.items.find((item) => item.id === record.id) ?? record, snapshot };
}

/** A collection's records. `projectId` is required for collections inside a project. */
export async function getSnapshot(slug: CollectionSlug, projectId?: string) {
  const scope = await resolveScope(slug, projectId);
  return toSnapshot(scope, await readData(scope));
}

function parseName(form: FormData): string {
  const raw = form.get("name");
  const name = typeof raw === "string" ? raw.trim() : "";
  if (!name) throw new ApiError(400, "Name is required.");
  if (name.length > NAME_MAX) throw new ApiError(400, `Name must be ${NAME_MAX} characters or fewer.`);
  return name;
}

/** The folder name for a new record whose ID comes from its name. */
function folderNameFor(name: string): string {
  const folder = slugify(name);
  if (!folder) throw new ApiError(400, "The name needs at least one letter or digit (A–Z, 0–9) to make a folder name.");
  if (DEVICE_NAME.test(folder)) throw new ApiError(400, `"${folder}" can't be used as a folder name. Choose another name.`);
  return folder;
}

/** Validates the uploaded files. Missing files are an error only for required fields of a new record. */
function parseFiles(slug: CollectionSlug, form: FormData, creating: boolean): Map<string, File> {
  const files = new Map<string, File>();
  for (const [key, field] of fileFieldsOf(slug)) {
    const value = form.get(key);
    if (!(value instanceof File) || value.size === 0) {
      if (creating && field.required) throw new ApiError(400, `A file for "${key}" is required.`);
      continue;
    }
    const problem = validateFile(value, field.rule);
    if (problem) throw new ApiError(400, problem);
    files.set(key, value);
  }
  return files;
}

/** Optional file fields to clear, from `remove` values. A field that also has a new upload is replaced instead. */
function parseRemovals(slug: CollectionSlug, form: FormData, files: Map<string, File>): string[] {
  const fields = collectionDef(slug).fileFields;
  const keys = new Set(form.getAll("remove").filter((value): value is string => typeof value === "string"));
  for (const key of keys) {
    if (!Object.hasOwn(fields, key)) throw new ApiError(400, `"${key}" isn't a file field.`);
    if (fields[key].required) throw new ApiError(400, `The "${key}" file is required, so it can't be removed.`);
  }
  return [...keys].filter((key) => !files.has(key));
}

/** Text fields (e.g. a ship's IMO number). Each save sends all of them; one left empty or out is removed. */
function parseTextFields(slug: CollectionSlug, form: FormData): Record<string, string> {
  const values: Record<string, string> = {};
  for (const [key, field] of textFieldsOf(slug)) {
    const raw = form.get(key);
    const { value, error } = checkTextField(field, typeof raw === "string" ? raw : "");
    if (error) throw new ApiError(400, error);
    if (value) values[key] = value;
  }
  return values;
}

/** Link fields (e.g. `objectIds`, one value per ID), not yet checked. The stored list is replaced on each save. */
function parseLinkIds(slug: CollectionSlug, form: FormData): Record<string, string[]> {
  return Object.fromEntries(
    linkKeysOf(slug).map((key) => [key, [...new Set(form.getAll(key).filter((v): v is string => typeof v === "string"))]]),
  );
}

/** Every linked ID must exist in the linked collection of the same ship. */
async function checkLinks(scope: Scope, links: Record<string, string[]>) {
  for (const [key, target] of Object.entries(collectionDef(scope.slug).links ?? {})) {
    const ids = links[key];
    if (ids.length === 0) continue;
    const existing = new Set((await readData(siblingScope(scope, target))).items.map((item) => item.id));
    const missing = ids.find((id) => !existing.has(id));
    if (missing) throw new ApiError(400, `${missing} no longer exists. Reload and pick again.`);
  }
}

/** Records in other collections of the same ship that link to this one, e.g. the sections using an object. */
async function findUsers(scope: Scope, id: string) {
  const users: { slug: CollectionSlug; record: StoredRecord }[] = [];
  for (const other of Object.keys(COLLECTIONS) as CollectionSlug[]) {
    const keys = Object.entries(collectionDef(other).links ?? {})
      .filter(([, target]) => target === scope.slug)
      .map(([key]) => key);
    if (keys.length === 0) continue;
    for (const record of (await readData(siblingScope(scope, other))).items) {
      if (keys.some((key) => (record[key] as string[]).includes(id))) users.push({ slug: other, record });
    }
  }
  return users;
}

/** The record a save uploads files for: its folder, and the ID and name an object's file names are made from. */
interface UploadTarget {
  folder: string;
  id: string;
  /** The name as of this save. A file keeps the name it was saved with when the record is renamed, as its folder does. */
  name: string;
}

/**
 * A new upload's stored name, unique so a replacement never overwrites the file it replaces before the record is saved.
 * A field with a view (an object's files) is named from the record's name and tagged with the view, e.g.
 * "fuel-pump-3d-3be0d14c.glb"; a name without letters or digits uses the ID instead ("obj-001-3d-…"). Others are
 * named after the field, e.g. "manual-a1c2e3f4.pdf".
 */
function storedNameFor(slug: CollectionSlug, field: string, extension: string, target: UploadTarget): string {
  const unique = crypto.randomBytes(4).toString("hex");
  const view = collectionDef(slug).fileFields[field]?.view;
  if (!view) return `${field}-${unique}.${extension}`;
  return viewFileName(slugify(target.name) || slugify(target.id), view, unique, extension);
}

async function saveUpload(scope: Scope, target: UploadTarget, field: string, file: File): Promise<StoredFile> {
  const { folder } = target;
  const extension = getExtension(file.name);
  const storedName = storedNameFor(scope.slug, field, extension, target);
  const view = collectionDef(scope.slug).fileFields[field]?.view;
  await fs.writeFile(path.join(recordDir(scope, folder), storedName), Buffer.from(await file.arrayBuffer()));
  return {
    name: file.name,
    size: file.size,
    type: file.type || "application/octet-stream",
    extension,
    storedName,
    url: fileUrl(scope, folder, storedName),
    uploadedAt: new Date().toISOString(),
    ...(view && { view }),
  };
}

async function deleteUploads(scope: Scope, folder: string, files: (StoredFile | undefined)[]) {
  await Promise.all(
    files.map((file) =>
      file && isStoredName(file.storedName)
        ? fs.rm(path.join(recordDir(scope, folder), file.storedName), { force: true })
        : undefined,
    ),
  );
}

/** Saves all uploads, or removes the ones already written if any of them fails. */
async function saveUploads(scope: Scope, target: UploadTarget, files: Map<string, File>) {
  const saved: Record<string, StoredFile> = {};
  try {
    for (const [field, file] of files) saved[field] = await saveUpload(scope, target, field, file);
  } catch (error) {
    await deleteUploads(scope, target.folder, Object.values(saved));
    throw error;
  }
  return saved;
}

/** The section file field whose uploads are read into MANUAL_DATA_FILE. */
const MANUAL_FIELD = "manual";
/** The section file field whose uploads start the generation of the section's React code. */
const LINE_DIAGRAM_FIELD = "lineDiagram";

/** A newly queued code generation, when a save uploads a section's line diagram; undefined otherwise. */
function codegenFor(
  slug: CollectionSlug,
  saved: Record<string, StoredFile>,
  options: { engine?: "sdk" | "cli"; drawingHash?: string } = {},
): SectionCodegen | undefined {
  const lineDiagram = slug === "sections" ? saved[LINE_DIAGRAM_FIELD] : undefined;
  return lineDiagram ? queueRun(lineDiagram.storedName, options) : undefined;
}

function hashDrawing(bytes: Uint8Array): string {
  return crypto.createHash("sha256").update(bytes).digest("hex");
}

/**
 * A save's change to a section's manual data: read from a newly uploaded manual, or null when the manual is removed.
 * Undefined when the manual isn't changing, and for other collections.
 */
async function readManualData(slug: CollectionSlug, files: Map<string, File>, removals: string[] = []) {
  if (slug !== "sections") return undefined;
  const manual = files.get(MANUAL_FIELD);
  if (manual) return buildManualData(new Uint8Array(await manual.arrayBuffer()));
  return removals.includes(MANUAL_FIELD) ? null : undefined;
}

/**
 * Writes a section's MANUAL_DATA_FILE, or with null removes it (the manual is gone, or nothing could be read from it).
 * Returns a function that puts the previous file back, for when the record then can't be saved.
 */
async function writeManualData(scope: Scope, folder: string, json: string | null) {
  const target = path.join(recordDir(scope, folder), MANUAL_DATA_FILE);
  const previous = await fs.readFile(target).catch(() => null);
  if (json === null) await fs.rm(target, { force: true });
  else await writeAtomic(target, json);
  return async () => {
    if (previous) await writeAtomic(target, previous);
    else await fs.rm(target, { force: true });
  };
}

/** Template files a new ship doesn't get: installed packages, build output, and its placeholder ship.json (the ship's own is written last). */
const TEMPLATE_SKIP = new Set(["node_modules", "dist", "ship.json"]);

/**
 * Fills a new ship's folder from the template (child/template), named after the folder: a ship's project without data,
 * whose code is the shared viewer (child/core, @shipdocs/viewer-core). Nothing of the viewer is copied, so a change to
 * it reaches every ship, existing or new, the next time each is built.
 */
async function copyTemplate(dir: string, folder: string) {
  const packageFile = path.join(dir, "package.json");
  try {
    await fs.cp(SHIP_TEMPLATE_DIR, dir, {
      recursive: true,
      filter: (source) => {
        const [top] = path.relative(SHIP_TEMPLATE_DIR, source).split(path.sep);
        return !TEMPLATE_SKIP.has(top) && !source.endsWith(".tsbuildinfo");
      },
    });
    const pkg = JSON.parse(await fs.readFile(packageFile, "utf8"));
    pkg.name = `ship-${folder}`;
    await writeAtomic(packageFile, `${JSON.stringify(pkg, null, 2)}\n`);
  } catch (error) {
    if (errorCode(error) !== "ENOENT") throw error;
    throw new ApiError(500, "The ship template (child/template, with its package.json) is missing, so the ship can't be created.");
  }
}

/** `projectId` is required for collections inside a project. */
export async function createRecord(
  slug: CollectionSlug,
  form: FormData,
  projectId?: string,
  options: { codegenEngine?: "sdk" | "cli" } = {},
) {
  const def = collectionDef(slug);
  const name = parseName(form);
  const folderName = def.folderFromName ? folderNameFor(name) : null;
  const files = parseFiles(slug, form, true);
  const texts = parseTextFields(slug, form);
  const links = parseLinkIds(slug, form);
  // Read before taking the lock, so a long manual doesn't hold up other saves.
  const manualData = await readManualData(slug, files);
  return withLock(async () => {
    // Resolved in the lock, so the ship can't be deleted while this is saved into it.
    const scope = await resolveScope(slug, projectId);
    await checkLinks(scope, links);
    const data = await readData(scope);
    const id = formatId(def.idPrefix, data.nextSeq);
    const folder = folderName ?? id;
    const dir = recordDir(scope, folder);
    await fs.mkdir(rootDir(scope), { recursive: true });
    try {
      await fs.mkdir(dir);
    } catch (error) {
      if (errorCode(error) !== "EEXIST") throw error;
      throw new ApiError(
        409,
        def.folderFromName
          ? `A ${def.noun} folder named "${folder}" already exists (child/${scope.dir}/${folder}). Choose another name.`
          : `The folder child/${scope.dir}/${folder} already exists. Remove it, then try again.`,
      );
    }
    try {
      // A ship is a whole viewer project; its ship.json, written below, makes it show up.
      if (slug === "projects") await copyTemplate(dir, folder);
      const saved = await saveUploads(scope, { folder, id, name }, files);
      if (manualData?.json) await writeManualData(scope, folder, manualData.json);
      const now = new Date().toISOString();
      const codegen = codegenFor(slug, saved, { engine: options.codegenEngine });
      const record: StoredRecord = {
        id,
        folder,
        name,
        createdAt: now,
        updatedAt: now,
        ...texts,
        ...saved,
        ...(manualData && { manualData: manualData.summary }),
        ...links,
        ...(codegen && { codegen }),
      };
      await writeRecord(scope, record);
      const nextSeq = data.nextSeq + 1;
      await writeAtomic(path.join(rootDir(scope), COUNTER_FILE), `${JSON.stringify({ nextSeq })}\n`);
      return savedResult(scope, { nextSeq, items: [...data.items, record] }, record);
    } catch (error) {
      await removeFolder(dir);
      throw error;
    }
  });
}

/** Renaming keeps the folder and the ID: neither ever changes. `projectId` is required for collections inside a project. */
export async function updateRecord(
  slug: CollectionSlug,
  id: string,
  form: FormData,
  projectId?: string,
  options: { codegenEngine?: "sdk" | "cli" } = {},
) {
  const name = parseName(form);
  const files = parseFiles(slug, form, false);
  const removals = parseRemovals(slug, form, files);
  const texts = parseTextFields(slug, form);
  const links = parseLinkIds(slug, form);
  // Read before taking the lock, so a long manual doesn't hold up other saves.
  const manualData = await readManualData(slug, files, removals);
  return withLock(async () => {
    const scope = await resolveScope(slug, projectId);
    await checkLinks(scope, links);
    const data = await readData(scope);
    const existing = data.items.find((item) => item.id === id);
    if (!existing) throw new ApiError(404, `${id} no longer exists.`);
    const { folder } = existing;
    let drawingHash: string | undefined;
    const newDrawing = slug === "sections" ? files.get(LINE_DIAGRAM_FIELD) : undefined;
    if (newDrawing) {
      const newBytes = Buffer.from(await newDrawing.arrayBuffer());
      drawingHash = hashDrawing(newBytes);
      const oldDrawing = existing[LINE_DIAGRAM_FIELD] as StoredFile | undefined;
      if (oldDrawing) {
        const oldBytes = await fs.readFile(path.join(recordDir(scope, folder), oldDrawing.storedName)).catch((error) => {
          if (errorCode(error) === "ENOENT") return null;
          throw error;
        });
        if (oldBytes && hashDrawing(oldBytes) === drawingHash) {
          files.delete(LINE_DIAGRAM_FIELD);
          drawingHash = undefined;
        }
      }
    }
    const saved = await saveUploads(scope, { folder, id, name }, files);
    // Fields without a new upload keep their existing file.
    const record: StoredRecord = { ...existing, ...saved, ...links, id, folder, name, updatedAt: new Date().toISOString() };
    for (const [key] of textFieldsOf(slug)) {
      if (texts[key]) record[key] = texts[key];
      else delete record[key];
    }
    for (const key of removals) delete record[key];
    if (manualData) record.manualData = manualData.summary;
    else if (manualData === null) delete record.manualData;
    // A new line diagram replaces any earlier generation; the routes then stop a job still working on the old one.
    const codegen = codegenFor(slug, saved, { engine: options.codegenEngine, drawingHash });
    if (codegen) record.codegen = codegen;
    let restoreManualData: (() => Promise<void>) | undefined;
    try {
      if (manualData !== undefined) restoreManualData = await writeManualData(scope, folder, manualData?.json ?? null);
      await writeRecord(scope, record);
    } catch (error) {
      await deleteUploads(scope, folder, Object.values(saved));
      await restoreManualData?.();
      throw error;
    }
    // Only remove replaced files once the new record is safely written.
    await deleteUploads(
      scope,
      folder,
      [...Object.keys(saved), ...removals].map((key) => existing[key] as StoredFile | undefined),
    );
    const next = { ...data, items: data.items.map((item) => (item.id === id ? record : item)) };
    return savedResult(scope, next, record);
  });
}

/**
 * Deletes the record's whole folder, including any files added to it in the editor. For a ship, that's its whole
 * viewer project: its code, sections, objects and their files. `projectId` is required for collections inside a project.
 */
export function deleteRecord(slug: CollectionSlug, id: string, projectId?: string) {
  return withLock(async () => {
    const def = collectionDef(slug);
    const scope = await resolveScope(slug, projectId);
    const data = await readData(scope);
    const existing = data.items.find((item) => item.id === id);
    if (!existing) throw new ApiError(404, `${id} no longer exists.`);
    const users = await findUsers(scope, id);
    if (users.length > 0) {
      const names = users.map(({ record }) => record.name).join(", ");
      const noun = collectionDef(users[0].slug).noun;
      throw new ApiError(
        409,
        `${id} is used by ${names}. Remove it from ${users.length === 1 ? `that ${noun}` : `those ${noun}s`} first.`,
      );
    }
    const dir = recordDir(scope, existing.folder);
    // The metadata file goes first, so the record is gone from the Library and the viewer even if a file is held open.
    await fs.rm(path.join(dir, def.metaFile), { force: true });
    try {
      await removeFolder(dir);
    } catch (error) {
      console.warn(`Deleted ${id}, but couldn't remove everything in child/${scope.dir}/${existing.folder}:`, error);
    }
    // A section's code versions are kept in the ship's codegen folder, by section ID.
    if (slug === "sections" && scope.projectFolder) {
      const versions = path.join(CHILD_DIR, ...projectDir(scope.projectFolder).split("/"), CODEGEN_DIR, id);
      await removeFolder(versions).catch((error) => console.warn(`Deleted ${id}, but couldn't remove its code versions:`, error));
    }
    const next = { ...data, items: data.items.filter((item) => item.id !== id) };
    return { snapshot: await toSnapshot(scope, next) };
  });
}

/** A section's code generation fields in section.json (`codegen`, `codegenVersions`, `codegenVersion`), checked. */
export interface CodegenState {
  /** The latest generation. */
  codegen?: SectionCodegen;
  /** Oldest first. */
  versions: CodegenVersion[];
  /** The version whose files are in the section's folder. */
  activeVersion?: number;
}

/** Where CodegenState's fields are kept in section.json. */
const CODEGEN_FIELDS = { codegen: "codegen", versions: "codegenVersions", activeVersion: "codegenVersion" } as const;

function readCodegenState(record: StoredRecord): CodegenState {
  return {
    codegen: readCodegen(record.codegen),
    versions: readCodegenVersions(record.codegenVersions),
    activeVersion: readActiveVersion(record.codegenVersion),
  };
}

/** A section as code generation needs it (see src/server/codegen/jobs.ts). */
export interface CodegenSection extends CodegenState {
  id: string;
  name: string;
  folder: string;
  /** Absolute path of the section's folder. */
  dir: string;
  lineDiagram?: StoredFile;
  /** IDs of the ship's objects the section uses, in the order they were picked. */
  objectIds: string[];
}

/** One of the ship's objects, as code generation needs it. */
export interface CodegenObject {
  id: string;
  name: string;
  /** Absolute path of the object's folder. */
  dir: string;
  lineDiagram: StoredFile;
  model: StoredFile;
}

export interface CodegenTarget {
  shipName: string;
  /** Absolute path of the ship's project folder, e.g. .../child/ships/mv-aurora. */
  shipDir: string;
  section: CodegenSection;
  /** Every section of the ship, oldest first, including `section`. */
  sections: CodegenSection[];
  /** The objects `section` uses, in the order they were picked; an ID whose object is gone is skipped. */
  objects: CodegenObject[];
}

/** Every ship, read fresh from disk: its ID, name and project folder (absolute). Read-only, so it doesn't take the lock. */
export async function listShips(): Promise<{ id: string; name: string; dir: string }[]> {
  return (await readData(PROJECTS)).items.map((project) => ({
    id: project.id,
    name: project.name,
    dir: path.join(CHILD_DIR, ...projectDir(project.folder).split("/")),
  }));
}

/** A section and its ship, read fresh from disk, or null if either is gone. Read-only, so it doesn't take the lock. */
export async function findCodegenTarget(projectId: string, sectionId: string): Promise<CodegenTarget | null> {
  const project = (await readData(PROJECTS)).items.find((item) => item.id === projectId);
  if (!project) return null;
  const scope = projectScope("sections", project.folder);
  const sections = (await readData(scope)).items.map(
    (record): CodegenSection => ({
      id: record.id,
      name: record.name,
      folder: record.folder,
      dir: recordDir(scope, record.folder),
      lineDiagram: record[LINE_DIAGRAM_FIELD] as StoredFile | undefined,
      objectIds: Array.isArray(record.objectIds) ? record.objectIds.filter((id): id is string => typeof id === "string") : [],
      ...readCodegenState(record),
    }),
  );
  const section = sections.find((item) => item.id === sectionId);
  if (!section) return null;
  const shipDir = path.join(CHILD_DIR, ...projectDir(project.folder).split("/"));
  // parseRecord made sure every object has both of its (required) files.
  const objectScope = projectScope("objects", project.folder);
  const shipObjects = new Map((await readData(objectScope)).items.map((record) => [record.id, record]));
  const objects = section.objectIds.flatMap((id): CodegenObject[] => {
    const record = shipObjects.get(id);
    if (!record) return [];
    const { name, folder, lineDiagram, model } = record;
    return [{ id, name, dir: recordDir(objectScope, folder), lineDiagram: lineDiagram as StoredFile, model: model as StoredFile }];
  });
  return { shipName: project.name, shipDir, section, sections, objects };
}

/**
 * Changes a section's code generation fields under the write lock, so it can't undo a save made at the same time.
 * `update` gets their current values and returns the ones to change (a field set to undefined is removed), or
 * undefined to change nothing. It may throw an ApiError. Returns the save's result, or null if the ship or section is
 * gone or nothing changed. The section's `updatedAt` is kept: it tells when a person last edited it.
 */
export function patchSectionCodegen(
  projectId: string,
  sectionId: string,
  update: (state: CodegenState, section: { lineDiagram?: StoredFile }) => Partial<CodegenState> | undefined,
) {
  return withLock(async () => {
    const project = (await readData(PROJECTS)).items.find((item) => item.id === projectId);
    if (!project) return null;
    const scope = projectScope("sections", project.folder);
    const data = await readData(scope);
    const existing = data.items.find((item) => item.id === sectionId);
    if (!existing) return null;
    const next = update(readCodegenState(existing), {
      lineDiagram: existing[LINE_DIAGRAM_FIELD] as StoredFile | undefined,
    });
    if (!next) return null;
    const record: StoredRecord = { ...existing };
    for (const [key, field] of Object.entries(CODEGEN_FIELDS) as [keyof CodegenState, string][]) {
      if (!(key in next)) continue;
      const value = next[key];
      if (value === undefined || (Array.isArray(value) && value.length === 0)) delete record[field];
      else record[field] = value;
    }
    await writeRecord(scope, record);
    return savedResult(scope, { ...data, items: data.items.map((item) => (item.id === sectionId ? record : item)) }, record);
  });
}

const CONTENT_TYPES: Record<string, string> = {
  png: "image/png",
  jpg: "image/jpeg",
  jpeg: "image/jpeg",
  webp: "image/webp",
  svg: "image/svg+xml",
  pdf: "application/pdf",
};

/** A file from a record's folder, e.g. ("mv-aurora", "sections", "engine-room", "manual-a1c2e3f4.pdf"). */
export async function readUpload(projectFolder: string, slug: string, folder: string, storedName: string) {
  if (
    !isProjectCollection(slug) ||
    !isFolderName("projects", projectFolder) ||
    !isFolderName(slug, folder) ||
    !isStoredName(storedName)
  ) {
    throw new ApiError(404, "File not found.");
  }
  try {
    const bytes = await fs.readFile(path.join(recordDir(projectScope(slug, projectFolder), folder), storedName));
    const contentType = CONTENT_TYPES[getExtension(storedName)] ?? "application/octet-stream";
    return { bytes, contentType };
  } catch (error) {
    if (["ENOENT", "ENOTDIR"].includes(errorCode(error) ?? "")) throw new ApiError(404, "File not found.");
    throw error;
  }
}
